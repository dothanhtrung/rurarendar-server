create table if not exists users
(
    username      text                                   not null
        unique,
    display_name  text,
    password_hash text                                   not null,
    role          text                                   not null
        constraint users_role_check
            check (role = ANY (ARRAY ['user'::text, 'admin'::text])),
    enabled       boolean                  default true  not null,
    created_at    timestamp with time zone default now() not null,
    updated_at    timestamp with time zone default now() not null,
    last_login_at timestamp with time zone,
    id            bigserial
        primary key
);

create table if not exists tokens
(
    username     text                                   not null,
    token_hash   bytea                                  not null
        unique,
    device_id    text,
    device_label text,
    created_at   timestamp with time zone default now() not null,
    expires_at   timestamp with time zone               not null,
    last_used_at timestamp with time zone,
    revoked_at   timestamp with time zone,
    user_id      bigint                                 not null
        references users
            on delete cascade,
    id           bigint generated by default as identity
        primary key
);

create index if not exists tokens_hash_live_idx
    on tokens (token_hash)
    where (revoked_at IS NULL);

create table if not exists user_seq
(
    last_seq bigint not null,
    user_id  bigint not null
        primary key
        references users
            on delete cascade
);

create table if not exists user_items
(
    sync_key           text                                   not null,
    item_type          text                                   not null
        constraint user_items_item_type_check
            check (item_type = ANY (ARRAY ['event'::text, 'hide_flag'::text])),
    rev                bigint                                 not null,
    deleted            boolean                  default false not null,
    seq                bigint                                 not null,
    updated_at         timestamp with time zone default now() not null,
    key_revision       integer                                not null,
    alg                text                                   not null,
    nonce              bytea                                  not null,
    ciphertext         bytea                                  not null,
    modified_timestamp timestamp with time zone default now() not null,
    item_id            bigint generated always as identity,
    user_id            bigint                                 not null
        references users
            on delete cascade,
    primary key (user_id, item_id)
);

create table if not exists user_crypto
(
    current_key_revision        integer default 0            not null,
    kdf_json                    jsonb,
    verifier_alg                text,
    verifier_nonce              bytea,
    verifier_ciphertext         bytea,
    rotation_status             text    default 'idle'::text not null
        constraint user_crypto_rotation_status_check
            check (rotation_status = ANY (ARRAY ['idle'::text, 'in_progress'::text])),
    from_key_revision           integer,
    to_key_revision             integer,
    pending_kdf_json            jsonb,
    pending_verifier_alg        text,
    pending_verifier_nonce      bytea,
    pending_verifier_ciphertext bytea,
    rotation_started_at         timestamp with time zone,
    user_id                     bigint                       not null
        primary key
        references users
            on delete cascade
);

create table if not exists admin_audit
(
    id              bigserial
        primary key,
    actor           text                                   not null,
    action          text                                   not null,
    target_username text,
    request_id      text,
    created_at      timestamp with time zone default now() not null
);

create table if not exists app_tokens
(
    token      text                                   not null
        unique,
    token_hash bytea                                  not null
        unique,
    expires_at timestamp with time zone,
    created_at timestamp with time zone default now() not null,
    user_id    bigint                                 not null
        unique
        references users
            on delete cascade,
    id         bigint generated by default as identity
        primary key
);

create table if not exists server_setup
(
    id        boolean default true not null
        primary key
        constraint server_setup_id_check
            check (id),
    completed boolean              not null
);

